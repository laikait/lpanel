    public function test_a_table_is_created_used_and_dropped(): void
    {
        $db = $this->sqlite();
        $db->execute('PRAGMA foreign_keys = ON');
        $db->tables()->create('customers', static function (Table $table): void {
            $table->id();
            $table->string('name', 100);
        });
        $db->tables()->create('invoices', self::invoices(...));

        $customer = $db->table('customers')->insert(['name' => 'Ada'], 'id');
        $invoice = $db->table('invoices')->insert(['customer_id' => $customer, 'number' => 'A-1'], 'id');

        self::assertSame(1, $invoice);
        self::assertSame(['number' => 'A-1', 'paid' => 0], $db->table('invoices')->select('number', 'paid')->first());

        foreach ([
            'a second invoice numbered A-1' => ['customer_id' => $customer, 'number' => 'A-1'],
            'an invoice for nobody' => ['customer_id' => 99, 'number' => 'A-2'],
        ] as $refusal => $row) {
            try {
                $db->table('invoices')->insert($row);
                self::fail(\sprintf('the database accepted %s', $refusal));
            } catch (DatabaseException) {
            }
        }

        $db->tables()->drop('invoices');
        self::assertSame(0, $db->scalar("SELECT COUNT(*) FROM sqlite_master WHERE name = 'invoices'"));
    }

    /** The rows already there keep their values through a change, and get the new column's default. */
    public function test_a_table_is_altered_with_its_rows_in_it(): void
    {
        $db = $this->sqlite();
        $db->execute('PRAGMA foreign_keys = ON');
        $db->tables()->create('customers', static function (Table $table): void {
            $table->id();
        });
        $db->tables()->create('invoices', static function (Table $table): void {
            $table->id();
            $table->bigInteger('customer_id')->index();
            $table->string('number', 30);
            $table->text('notes')->nullable();
        });
        $db->table('invoices')->insert(['customer_id' => 7, 'number' => 'A-1', 'notes' => 'gone soon']);

        $db->tables()->alter('invoices', self::change(...));
        $db->tables()->alter('invoices', static function (Table $table): void {
            $table->bigInteger('account_id')->nullable();
            $table->foreign('account_id')->references('customers');
        });

        self::assertSame(
            ['id' => 1, 'customer_id' => 7, 'code' => 'A-1', 'reference' => null, 'copies' => 1, 'account_id' => null],
            $db->table('invoices')->first(),
        );

        $db->table('invoices')->insert(['customer_id' => 7, 'code' => 'A-2']);

        foreach ([
            'a reference used twice' => ['customer_id' => 7, 'code' => 'A-3', 'reference' => 'R'],
            'an account that does not exist' => ['customer_id' => 7, 'code' => 'A-4', 'account_id' => 99],
        ] as $refusal => $row) {
            try {
                $db->table('invoices')->insert($row);
                $db->table('invoices')->insert($row);
                self::fail(\sprintf('the database accepted %s', $refusal));
            } catch (DatabaseException) {
            }
        }
    }

    /** Pretending, the change is written and nothing is sent. */
    public function test_a_pretended_change_changes_nothing(): void
    {
        $db = $this->sqlite();
        $db->tables()->create('invoices', static function (Table $table): void {
            $table->id();
        });

        $tables = $db->tables(pretend: true);
        $tables->alter('invoices', static function (Table $table): void {
            $table->string('number', 30)->nullable();
        });

        self::assertSame([['sql' => 'ALTER TABLE "invoices" ADD COLUMN "number" TEXT NULL', 'raw' => false]], $tables->statements());
        $db->table('invoices')->insert(['id' => 1]);
        self::assertSame(['id' => 1], $db->table('invoices')->first());
    }

    /** A string default is quoted by the driver, so a quote in it stays a quote. */
    public function test_a_default_with_a_quote_in_it_is_written_by_the_driver(): void
    {
        $db = $this->sqlite();
        $db->tables()->create('notes', static function (Table $table): void {
            $table->id();
            $table->string('body')->default("it's '; DROP TABLE notes; --");
        });

        $db->table('notes')->insert(['id' => 1]);

        self::assertSame("it's '; DROP TABLE notes; --", $db->table('notes')->where('id', 1)->first()['body'] ?? null);
    }

