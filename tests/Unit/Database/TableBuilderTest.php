    /** @param list<string> $expected */
    #[DataProvider('types')]
    public function test_every_type_has_a_name_in_every_dialect(string $driver, array $expected): void
    {
        [$create] = self::compile($driver, static function (Table $table): void {
            $table->integer('a');
            $table->bigInteger('b');
            $table->decimal('c', 8, 3);
            $table->string('d');
