        }
    }

    /** SQL Server alone counts NULLs as equal in a unique index; its index leaves them out. */
    public function test_a_nullable_unique_column_on_sql_server_lets_many_rows_hold_null(): void
    {
        $statements = self::compile('sqlsrv', static function (Table $table): void {
            $table->string('email')->nullable()->unique();
            $table->string('code')->unique();
            $table->string('region')->nullable();
            $table->unique('code', 'region');
        }, 'people');

        self::assertSame('CREATE UNIQUE INDEX [people_email_unique] ON [people] ([email]) WHERE [email] IS NOT NULL', $statements[1]);
        self::assertSame('CREATE UNIQUE INDEX [people_code_unique] ON [people] ([code])', $statements[2]);
        self::assertSame('CREATE UNIQUE INDEX [people_code_region_unique] ON [people] ([code], [region]) WHERE [region] IS NOT NULL', $statements[3]);
        self::assertStringNotContainsString('WHERE', self::compile('pgsql', static function (Table $table): void {
            $table->string('email')->nullable()->unique();
        }, 'people')[1]);
    }

    /**
     * A plain '...' is VARCHAR to SQL Server, in the server's code page, and
     * কলকাতা would reach the NVARCHAR column as question marks. CI caught it.
     */
    public function test_a_string_default_on_sql_server_is_a_unicode_literal(): void
    {
        [$create] = self::compile('sqlsrv', static function (Table $table): void {
            $table->string('city', 50)->default('কলকাতা');
            $table->decimal('total', 12, 2)->default('0.00');
        });

        self::assertStringContainsString("[city] NVARCHAR(50) NOT NULL DEFAULT N'কলকাতা'", $create);
        self::assertStringContainsString("[total] DECIMAL(12,2) NOT NULL DEFAULT '0.00'", $create);
        self::assertStringContainsString("DEFAULT 'কলকাতা'", self::compile('pgsql', static function (Table $table): void {
            $table->string('city', 50)->default('কলকাতা');
        })[0]);
    }

    /** A key that is not a counted id: a session id, a country code. */
    public function test_a_string_key_in_each_dialect(): void
    {
        $key = static function (Table $table): void {
            $table->string('code', 2)->primary();
            $table->string('name', 80)->default('');
        };

        self::assertStringStartsWith('CREATE TABLE `countries` (`code` VARCHAR(2) NOT NULL PRIMARY KEY, ', self::compile('mysql', $key, 'countries')[0]);
        self::assertStringStartsWith('CREATE TABLE "countries" ("code" VARCHAR(2) NOT NULL PRIMARY KEY, ', self::compile('pgsql', $key, 'countries')[0]);
        self::assertStringStartsWith('CREATE TABLE "countries" ("code" TEXT NOT NULL PRIMARY KEY, ', self::compile('sqlite', $key, 'countries')[0]);
        self::assertStringStartsWith('CREATE TABLE [countries] ([code] NVARCHAR(2) NOT NULL PRIMARY KEY, ', self::compile('sqlsrv', $key, 'countries')[0]);
        self::assertStringContainsString('[name] NVARCHAR(80) NOT NULL DEFAULT N\'\'', self::compile('sqlsrv', $key, 'countries')[0]);
    }

