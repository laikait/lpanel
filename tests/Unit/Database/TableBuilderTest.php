    /** @return list<string> */
    private static function compile(string $driver, \Closure $define, string $name = 'invoices'): array
    {
        $table = new Table($name);
        $define($table);

        return Grammar::for($driver)->compileCreateTable(
            $table,
            static fn(string $value): string => "'" . \str_replace("'", "''", $value) . "'",
        );
    }

    /** @return list<string> */
    private static function alter(string $driver, \Closure $define, string $name = 'invoices'): array
    {
        $table = new Table($name, altering: true);
        $define($table);

        return Grammar::for($driver)->compileAlterTable(
            $table,
            static fn(string $value): string => "'" . \str_replace("'", "''", $value) . "'",
        );
    }

    private static function invoices(Table $table): void
    {
        $table->id();
        $table->bigInteger('customer_id')->index();
        $table->string('number', 30)->unique();
        $table->decimal('total', 12, 2)->default('0.00');
        $table->boolean('paid')->default(false);
        $table->dateTime('issued_at')->nullable();
        $table->foreign('customer_id')->references('customers')->onDelete('restrict');
    }

    private function sqlite(): Connection
    {
        return new Connection(ConnectionConfig::of('test', 'sqlite::memory:'));
    }

