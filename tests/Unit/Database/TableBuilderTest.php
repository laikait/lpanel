    // ---- altering ------------------------------------------------------------

    private static function change(Table $table): void
    {
        $table->string('reference', 40)->nullable()->unique();
        $table->integer('copies')->default(1);
        $table->dropColumn('notes');
        $table->renameColumn('number', 'code');
        $table->dropIndex('customer_id');
    }

    /** @return array<string, array{string, list<string>}> */
    public static function alterations(): array
    {
        return [
            'mysql' => ['mysql', [
                'DROP INDEX `invoices_customer_id_index` ON `invoices`',
                'ALTER TABLE `invoices` DROP COLUMN `notes`',
                'ALTER TABLE `invoices` RENAME COLUMN `number` TO `code`',
                'ALTER TABLE `invoices` ADD COLUMN `reference` VARCHAR(40) NULL',
                'ALTER TABLE `invoices` ADD COLUMN `copies` INT NOT NULL DEFAULT 1',
                'CREATE UNIQUE INDEX `invoices_reference_unique` ON `invoices` (`reference`)',
            ]],
            'pgsql' => ['pgsql', [
                'DROP INDEX "invoices_customer_id_index"',
                'ALTER TABLE "invoices" DROP COLUMN "notes"',
                'ALTER TABLE "invoices" RENAME COLUMN "number" TO "code"',
                'ALTER TABLE "invoices" ADD COLUMN "reference" VARCHAR(40) NULL',
                'ALTER TABLE "invoices" ADD COLUMN "copies" INTEGER NOT NULL DEFAULT 1',
                'CREATE UNIQUE INDEX "invoices_reference_unique" ON "invoices" ("reference")',
            ]],
            'sqlite' => ['sqlite', [
                'DROP INDEX "invoices_customer_id_index"',
                'ALTER TABLE "invoices" DROP COLUMN "notes"',
                'ALTER TABLE "invoices" RENAME COLUMN "number" TO "code"',
                'ALTER TABLE "invoices" ADD COLUMN "reference" TEXT NULL',
                'ALTER TABLE "invoices" ADD COLUMN "copies" INTEGER NOT NULL DEFAULT 1',
                'CREATE UNIQUE INDEX "invoices_reference_unique" ON "invoices" ("reference")',
            ]],
            // The default's made-up name is looked up and dropped before its column.
            'sqlsrv' => ['sqlsrv', [
                'DROP INDEX [invoices_customer_id_index] ON [invoices]',
                'SET NOCOUNT ON; DECLARE @default SYSNAME, @sql NVARCHAR(MAX); '
                . 'SELECT @default = d.name FROM sys.default_constraints d '
                . 'JOIN sys.columns c ON c.object_id = d.parent_object_id AND c.column_id = d.parent_column_id '
                . "WHERE d.parent_object_id = OBJECT_ID(N'[invoices]') AND c.name = N'notes'; "
                . "IF @default IS NOT NULL BEGIN SET @sql = N'ALTER TABLE [invoices] DROP CONSTRAINT ' + QUOTENAME(@default); EXEC sp_executesql @sql; END; "
                . 'ALTER TABLE [invoices] DROP COLUMN [notes]',
                "EXEC sp_rename N'[invoices].[number]', N'code', N'COLUMN'",
                'ALTER TABLE [invoices] ADD [reference] NVARCHAR(40) NULL',
                'ALTER TABLE [invoices] ADD [copies] INT NOT NULL DEFAULT 1',
                'CREATE UNIQUE INDEX [invoices_reference_unique] ON [invoices] ([reference]) WHERE [reference] IS NOT NULL',
            ]],
        ];
    }

    /**
     * Whatever order the change was described in, what goes goes first, then
     * the renames, then what comes.
     *
     * @param list<string> $expected
     */
    #[DataProvider('alterations')]
    public function test_one_change_is_written_in_each_dialect(string $driver, array $expected): void
    {
        self::assertSame($expected, self::alter($driver, self::change(...)));
    }

    /** @return array<string, array{string, list<string>}> */
    public static function foreignKeyChanges(): array
    {
        $add = static fn(string $q): string => \sprintf(
            'ALTER TABLE %1$sinvoices%2$s ADD CONSTRAINT %1$sinvoices_account_id_foreign%2$s FOREIGN KEY (%1$saccount_id%2$s) '
            . 'REFERENCES %1$saccounts%2$s (%1$sid%2$s) ON DELETE SET NULL ON UPDATE NO ACTION',
            $q[0],
            $q[1],
        );

        return [
            'mysql' => ['mysql', [
                'ALTER TABLE `invoices` DROP FOREIGN KEY `invoices_customer_id_foreign`',
                'ALTER TABLE `invoices` ADD COLUMN `account_id` BIGINT NULL',
                $add('``'),
            ]],
            'pgsql' => ['pgsql', [
                'ALTER TABLE "invoices" DROP CONSTRAINT "invoices_customer_id_foreign"',
                'ALTER TABLE "invoices" ADD COLUMN "account_id" BIGINT NULL',
                $add('""'),
            ]],
            'sqlsrv' => ['sqlsrv', [
                'ALTER TABLE [invoices] DROP CONSTRAINT [invoices_customer_id_foreign]',
                'ALTER TABLE [invoices] ADD [account_id] BIGINT NULL',
                $add('[]'),
            ]],
        ];
    }

    /** @param list<string> $expected */
    #[DataProvider('foreignKeyChanges')]
    public function test_foreign_keys_are_dropped_and_added_by_name(string $driver, array $expected): void
    {
        self::assertSame($expected, self::alter($driver, static function (Table $table): void {
            $table->dropForeign('customer_id');
            $table->bigInteger('account_id')->nullable();
            $table->foreign('account_id')->references('accounts')->onDelete('set null');
        }));
    }

    /** SQLite's ALTER TABLE has no constraints, but a new column can carry its own REFERENCES. */
    public function test_sqlite_writes_a_new_columns_foreign_key_with_the_column(): void
    {
        self::assertSame(
            ['ALTER TABLE "invoices" ADD COLUMN "account_id" INTEGER NULL CONSTRAINT "invoices_account_id_foreign" '
            . 'REFERENCES "accounts" ("id") ON DELETE SET NULL ON UPDATE NO ACTION'],
            self::alter('sqlite', static function (Table $table): void {
                $table->bigInteger('account_id')->nullable();
                $table->foreign('account_id')->references('accounts')->onDelete('set null');
            }),
        );
    }

    /** @return array<string, array{\Closure(Table): mixed, string}> */
    public static function sqliteCannot(): array
    {
        return [
            'drop a foreign key' => [static fn(Table $t) => $t->dropForeign('customer_id'), 'cannot drop the foreign key on "customer_id"'],
            'key a column already there' => [
                static fn(Table $t) => $t->foreign('customer_id')->references('customers'),
                'cannot add a foreign key to the column "customer_id", which is already there',
            ],
            'key a new column with a default' => [static function (Table $t): void {
                $t->bigInteger('account_id')->default(1);
                $t->foreign('account_id')->references('accounts');
            }, 'unless it is nullable with no default'],
        ];
    }

    /** Refused, not done by rebuilding the table -- and refused before anything is sent. */
    #[DataProvider('sqliteCannot')]
    public function test_what_sqlite_cannot_alter_is_refused_with_the_way_round_it(\Closure $define, string $message): void
    {
        try {
            self::alter('sqlite', static function (Table $t) use ($define): void {
                $t->string('first', 10)->nullable();
                $define($t);
            });
            self::fail('SQLite was given a change it has no statement for');
        } catch (DatabaseException $e) {
            self::assertStringContainsString($message, $e->getMessage());
            self::assertStringContainsString('Nothing was run. The way there is a new table', $e->getMessage());
        }
    }

    public function test_an_index_in_a_schema_is_dropped_from_the_schema(): void
    {
        self::assertSame(['DROP INDEX "sales"."orders_placed_at_index"'], self::alter('pgsql', static fn(Table $t) => $t->dropIndex('placed_at'), 'sales.orders'));
        self::assertSame(['DROP INDEX `orders_placed_at_index` ON `sales`.`orders`'], self::alter('mysql', static fn(Table $t) => $t->dropIndex('placed_at'), 'sales.orders'));
    }

